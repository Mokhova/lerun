/** Nearest preset to an arbitrary stored value — old projects keep working. */
export const nearest = <T extends { id: number }>(list: T[], value: number): number =>
  list.reduce((best, o) => (Math.abs(o.id - value) < Math.abs(best - value) ? o.id : best), list[0].id)

/**
 * The spot one step in a given direction — what an arrow key should reach.
 * Movement along the pressed axis is what counts; drift across it is penalised
 * so ↑ from «снизу слева» lands on «сверху слева», not on the centre.
 */
export function neighbourSpot(from: string, dx: -1 | 0 | 1, dy: -1 | 0 | 1): string | null {
  const here = PATTERN_SPOTS.find((s) => s.id === from)
  if (!here) return null
  let best: { id: string; score: number } | null = null
  for (const s of PATTERN_SPOTS) {
    if (s.id === here.id) continue
    const along = dx ? (s.fx - here.fx) * dx : (s.fy - here.fy) * dy
    const across = dx ? Math.abs(s.fy - here.fy) : Math.abs(s.fx - here.fx)
    if (along <= 0.01) continue
    const score = along + across * 3
    if (!best || score < best.score) best = { id: s.id, score }
  }
  return best?.id ?? null
}
