/**
 * Generates:
 *   src/styles/fonts.css      — @font-face rules that point at /fonts/*.woff2 (used by the app)
 *   src/fonts/embedCss.ts     — the same faces with base64 data URIs (used by PNG export,
 *                               so html-to-image never has to fetch anything)
 * Only the `cyrillic` and `latin` subsets are inlined — that is what this editor writes in.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'scripts/_google-local.css'), 'utf8')

const KEEP_FOR_EMBED = new Set(['cyrillic', 'latin'])

const blocks = []
const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g
let m
while ((m = re.exec(src))) blocks.push({ subset: m[1], body: m[2].trim() })

const rhythmic = `@font-face {
  font-family: 'Rhythmic RUS';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url(/fonts/Rhythmic_RUS.woff2) format('woff2');
}`

const userFonts = [
  { family: 'SONGER', file: 'SONGER-C-Regular.otf', style: 'normal', weight: 400, format: 'opentype' },
  { family: 'Gilroy', file: 'Gilroy-Regular-cyr.woff2', style: 'normal', weight: 400, format: 'woff2' },
  { family: 'Gilroy', file: 'Gilroy-Medium-cyr.woff2', style: 'normal', weight: 500, format: 'woff2' },
  { family: 'Gilroy', file: 'Gilroy-Bold-cyr.woff2', style: 'normal', weight: 700, format: 'woff2' },
  { family: 'Gilroy', file: 'Gilroy-BoldItalic-cyr.woff2', style: 'italic', weight: 700, format: 'woff2' },
]

const userFontFaces = userFonts.map(({ family, file, style, weight, format }) => `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url(/fonts/${file}) format('${format}');
}`)

const appCss = [
  '/* GENERATED by scripts/build-font-embed.mjs — do not edit by hand */',
  rhythmic,
  ...userFontFaces,
  ...blocks.map((b) => `/* ${b.subset} */\n@font-face {\n  ${b.body}\n}`),
].join('\n\n')
writeFileSync(join(root, 'src/styles/fonts.css'), appCss + '\n')

const b64 = (p) => readFileSync(join(root, 'public', p)).toString('base64')
const inline = (body) =>
  body.replace(/url\((\/fonts\/[^)]+\.(?:woff2|otf))\)/g, (_, p) => {
    const mime = p.endsWith('.otf') ? 'font/otf' : 'font/woff2'
    return `url(data:${mime};base64,${b64(p)})`
  })

const embed = [
  inline(rhythmic),
  ...userFontFaces.map(inline),
  ...blocks.filter((b) => KEEP_FOR_EMBED.has(b.subset)).map((b) => `@font-face{${inline(b.body)}}`),
].join('\n')

writeFileSync(
  join(root, 'src/fonts/embedCss.ts'),
  '/* GENERATED by scripts/build-font-embed.mjs — do not edit by hand */\n' +
    '// Fonts as data URIs so PNG export is deterministic and works offline.\n' +
    'export const FONT_EMBED_CSS = ' + JSON.stringify(embed) + '\n'
)

console.log(
  `fonts.css: ${blocks.length + 1} faces · embedCss.ts: ${
    embed.length / 1024 | 0
  } KB`
)
